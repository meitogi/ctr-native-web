/** The words for a refusal from resolveDisc / probeDisc / a storage error. */
export function errorText(t, failure) {
  const e = t.errors[failure?.reason] ?? t.errors.unknown
  if (typeof e === 'function') {
    const serial = /([A-Z]{4}_\d{3}\.\d{2})/.exec(failure?.message ?? '')?.[1]
    return e(serial?.replace('_', '-').replace('.', ''))
  }
  return e
}
